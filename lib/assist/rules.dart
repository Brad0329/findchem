/// 쓸 수 있는 주제(원문 적용 순서).
const ruleTopics = ['byeolpyo2', 'byeolpyo3', 'byeolpyo4', 'byeolpyo1'];

/// [topic]의 규칙 원문. `all`이면 전부 이어 붙인다.
///
/// 알 수 없는 주제는 [UnknownRuleTopic]을 던진다 — 조용히 전체로 대체하지 않는다.
String getRule(String topic) {
  final String body;
  if (topic == 'all') {
    body = ruleTopics.map((t) => rules[t]!).join('\n\n');
  } else {
    final one = rules[topic];
    if (one == null) throw UnknownRuleTopic(topic);
    body = one;
  }
  return '출처: $notice\n\n$body';
}

